"""Log completed frozen disturbance tests to the isolated research experiment."""
import argparse, hashlib, json, zipfile
from pathlib import Path
import mlflow
import numpy as np

R = Path(__file__).parent
B = R/'learned_geometry_branch'
read = lambda p: json.loads(p.read_text())
sha = lambda p: hashlib.sha256(p.read_bytes()).hexdigest()

def main():
    p = argparse.ArgumentParser()
    p.add_argument('--commit', required=True)
    p.add_argument('--source-archive', type=Path, required=True)
    a = p.parse_args()
    assert len(a.commit) == 40 and all(c in '0123456789abcdef' for c in a.commit)
    aggregate = read(B/'stack_reserved_test_summary300.json')
    freeze = read(B/'stack_reserved_test_freeze.json')
    assert aggregate['complete'] and aggregate['completed_episodes'] == 300
    mlflow.set_tracking_uri('http://127.0.0.1:5055')
    client = mlflow.MlflowClient()
    exp = client.get_experiment_by_name('comp0245-directed-control-rnd')
    assert exp
    receipts = []
    for seed in [7, 1, 2]:
        adapter = B/('stack_recovery_reserved_recording_adapter_v1' if seed == 7 else f'stack_reserved_seed{seed}_v1')
        d = adapter/f'test_seed{seed}'
        audit, cfg = read(d/'reserved_audit.json'), read(d/'config.json')
        assert audit['complete'] and audit['completed'] == 100 and cfg['test'] and cfg['split'] == 'test'
        assert all(sha(adapter/path) == value for path, value in freeze['source_hashes'].items())
        assert (d/'replay_receipt.json').exists()
        archive = R/f'stack_test100_noise{seed}_recordings.zip'
        if not archive.exists():
            temporary = archive.with_suffix('.tmp')
            with zipfile.ZipFile(temporary, 'w', zipfile.ZIP_DEFLATED, compresslevel=1) as z:
                for file in sorted(d.rglob('*')):
                    if file.is_file(): z.write(file, file.relative_to(d))
            temporary.replace(archive)
        artifact = dict(name=archive.name, bytes=archive.stat().st_size, sha256=sha(archive))
        receipt_path = R/f'publication_stack_noise{seed}_mlflow.json'
        if receipt_path.exists():
            receipt = read(receipt_path)
            runid = receipt['run_id']
        else:
            run = client.create_run(exp.experiment_id, tags={'mlflow.runName':f'rnd-disturbance-reference-recovery-noise{seed}-test100', 'run_role':'frozen_research_test'})
            runid = run.info.run_id
            receipt = dict(run_id=runid, experiment_id=exp.experiment_id, verified=False)
            receipt_path.write_text(json.dumps(receipt, indent=2))
        url = f'https://nm-linmint-mlflow.taile381c0.ts.net:8443/golden-replays/directed-control-rnd/learned_geometry_branch/{adapter.name}/{d.name}/viewer_{d.name}.html'
        description = (f'Frozen engineered-control extension, sensor-noise seed {seed}; not a new training seed. '
            'Learned geometry and torque coefficients with explicit feedback; original driving checkpoint remains frozen. '
            'Encoder noise, damping, elasticity, inertia, nominal 3 ms delay and recorded random starts enabled. '
            'No DART, DAgger, occlusion or bursty recording loss. Settings selected on validation only. '
            'Same 100 historically used targets across three noise realisations, not 300 independent target locations. '
            'Every timeout retained; no test-guided tuning or selective reruns. '
            'Offline geometry uses recorded simulator pose labels; torque identification uses expert internal references. '
            'Runtime references are generated by the controller and runtime target/position estimates use sensors. '
            'Identified feedforward torque is gravity-like compensation. Geometric STOP threshold 5 mm; canonical score 10 mm. '
            'Settling checks all 1 kHz samples for 0.5 s after STOP. '
            'Original completion receipt has an inherited validation label; config.split/test and the derived audit identify this reserved test. '
            f'Replay: {url} . Source: https://github.com/NatMota/mlai-vnc/tree/{a.commit}/research/directed_control .')
        with mlflow.start_run(run_id=runid):
            mlflow.set_tags({'mlflow.note.content':description, 'git.commit':a.commit, 'mlflow.source.git.commit':a.commit,
                'evaluation_split':'test', 'original_project_modified':'false', 'test_outcome_tuning':'false',
                'historical_test_exposure':'true', 'architecture':'learned_geometry_identified_torque_explicit_feedback',
                'replication_axis':'sensor_noise_seed', 'same_targets_across_noise_seeds':'true'})
            mlflow.log_params(dict(train_targets=100, validation_targets=100, test_targets=100, driving_training_seed=7,
                sensor_noise_seed=seed, DART=False, DAgger=False, arm_rate_hz=1000, camera_driving_hz=30,
                stop_threshold_mm=5, success_threshold_mm=10, settling_duration_s=.5, cartesian_gain=2.5,
                reference_speed_cap_rad_s=.5, cartesian_damping=40, reference_recovery_rad_s=.1,
                native_sha256=cfg['native_sha256'], freeze_timestamp=freeze['timestamp_utc'],
                source_archive_sha256=sha(a.source_archive), **cfg['condition']))
            metrics = {'test/attempts':100, 'test/PARK':audit['PARK'], 'test/STOP':audit['STOP'],
                'test/success_10mm':audit['canonical_success'], 'test/settled_success_10mm':audit['canonical_success_and_settled'],
                'test/internal_motion_flags':len(audit['internal_diagnostic_flags']),
                'validation/success_10mm':98, 'validation/settled_success_10mm':98}
            for key in ['STOP_mm', 'final_mm', 'exact_postSTOP_peak_mm', 'actual_sent_peak_Nm']:
                values = [row[key] for row in audit['rows'] if row.get(key) is not None]
                for label, q in [('median', .5), ('p95', .95), ('max', 1)]:
                    metrics[f'test/{label}_{key}'] = float(np.quantile(values, q))
            mlflow.log_metrics(metrics)
            for name in ['position.npz', 'torque.npz', 'hybrid_bounds.npz']:
                mlflow.log_artifact(str(adapter/'models'/name), 'models')
            mlflow.log_artifact(str(adapter/'baseline/driving_seed7.npz'), 'models')
            for name in ['reserved_audit.json', 'frame_alignment_audit.json', 'config.json', 'completion.json', 'summary.json', 'replay_receipt.json']:
                mlflow.log_artifact(str(d/name), 'test')
            for name in ['stack_reserved_test_plan.json', 'stack_reserved_test_freeze.json', 'stack_reserved_test_data_receipt.json', 'stack_reserved_test_summary300.json']:
                mlflow.log_artifact(str(B/name), 'freeze')
            for folder in ['trig_position_training', 'identified_torque_training']:
                for name in ['summary.json', 'config.json', 'audit.json']:
                    mlflow.log_artifact(str(R/folder/name), 'fitting/'+folder)
            for name in ['research_notebook.ipynb', 'research_notebook.html', 'ARCHITECTURE.md']:
                mlflow.log_artifact(str(R/name), 'notebook')
            mlflow.log_artifact(str(a.source_archive), 'source')
            bundle = B/'stack_recovery_reserved_recording_adapter_v1/portable_source_models.tar.gz'
            mlflow.log_artifact(str(bundle), 'source')
            mlflow.log_artifact(str(bundle.with_name('portable_archive_receipt.json')), 'source')
            mlflow.log_artifact(str(archive), 'recordings')
            mlflow.log_dict(artifact, 'recordings/archive_receipt.json')
        run = client.get_run(runid)
        assert run.info.status == 'FINISHED' and run.data.metrics['test/attempts'] == 100
        assert any(x.path.endswith(archive.name) for x in client.list_artifacts(runid, 'recordings'))
        receipt.update(verified=True, source_commit=a.commit, recordings=artifact, replay=url,
            url=f'https://nm-linmint-mlflow.taile381c0.ts.net/#/experiments/{exp.experiment_id}/runs/{runid}')
        receipt_path.write_text(json.dumps(receipt, indent=2))
        receipts.append(receipt)
        print(json.dumps(receipt), flush=True)
    (R/'publication_stack_mlflow.json').write_text(json.dumps(receipts, indent=2))

if __name__ == '__main__': main()
